-- ===========================================================================
-- 0002_attachments —— 消息可以带附件
-- ---------------------------------------------------------------------------
-- 附件有两种（见 models.rs 的 ChatAttachment）：
--   file       ：读到的本地文件内容，拼接进 prompt 的文本部分
--   screenshot ：截图，走 OpenAI 的 image_url 多模态格式
--
-- 为什么把内容**存进消息里**，而不是只存一个「来自哪个文件」的引用：
-- 多轮对话每次都要把整段历史重发给模型。如果历史消息里的图片只剩一个引用，
-- 第二轮开始模型就看不到那张图了 —— 用户问「这个报错什么意思」会得到一脸茫然。
-- 所以附件内容必须跟着消息一起留下来。
--
-- 代价要说清楚：文件内容会被复制进这份本地数据库，截图（可能包含屏幕上的
-- 任何东西）也会随消息落盘。这是「把附件发进对话」这个动作本身的一部分，
-- 界面上有对应的说明；「重置本地数据」会一并清掉。
--
-- 存 JSON 文本而不是单开一张表：附件的结构还在演进，
-- 而且没有任何按附件查询的需求，多一张表只会多一层 join。
-- ===========================================================================

ALTER TABLE messages ADD COLUMN attachments TEXT NOT NULL DEFAULT '[]';
